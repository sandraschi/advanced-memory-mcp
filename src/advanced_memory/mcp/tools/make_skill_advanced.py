def _ensure_valid_frontmatter(content: str, slug: str, topic: str) -> str:
    """Deterministically repair YAML frontmatter (2026-07-17).

    Small local models routinely emit frontmatter without the closing '---',
    which fails agentskills validation on every check. An LLM review loop is
    the wrong tool for a mechanical fix, so: extract whatever name/description
    survive, force name to the directory slug (name_matches_directory check),
    and rebuild a canonical frontmatter block around the remaining body.
    """
    import re as _re

    text = content.strip()
    if text.startswith("---"):
        rest = text[3:]
        close = _re.search(r"\n---\s*(?:\n|$)", rest)
        if close:
            fm_block = rest[: close.start()]
            body = rest[close.end():]
        else:
            lines = rest.lstrip("\n").split("\n")
            fm_lines: list[str] = []
            body_lines: list[str] = []
            for i, ln in enumerate(lines):
                if _re.match(r"^[A-Za-z_][\w-]*:\s?", ln):
                    fm_lines.append(ln)
                else:
                    body_lines = lines[i:]
                    break
            fm_block = "\n".join(fm_lines)
            body = "\n".join(body_lines)
    else:
        fm_block = ""
        body = text

    desc_m = _re.search(r"^description:\s*(.+)$", fm_block, _re.M)
    description = (
        desc_m.group(1).strip().strip('"').strip("'")
        if desc_m
        else f"Expert knowledge on {topic} based on chained research"
    )[:1000]
    return f"---\nname: {slug}\ndescription: {description}\n---\n\n{body.strip()}\n"


async def _research_first_create_operation(
    topic: str,
    skill_name: str | None,
    output_path: str | None,
    research_sources: list[str],
    max_research_iterations: int,
    enable_review_loop: bool,
) -> dict[str, Any]:
    """Create skill via research chain: run_chain -> LLM SKILL.md -> scaffold -> validate."""
    import re

    from advanced_memory.services.llm_client import get_llm_client
    from advanced_memory.services.skill_creator import (
        scaffold_references_from_research,
        scaffold_skill,
        validate_skill_agentskills,
    )
    from advanced_memory.services.skill_research_chain import run_chain

    logger.info("research_first_create: starting chain for topic=%s", topic)

    valid_sources = ["arxiv", "github", "rag", "web"]
    sources = [s for s in research_sources if s in valid_sources] or valid_sources
    max_iter = max(1, min(5, max_research_iterations))

    try:
        bundle = await run_chain(
            topic=topic,
            sources=sources,
            max_iterations=max_iter,
            coverage_threshold=0.85,
        )
    except Exception as exc:
        logger.exception("research_first_create: run_chain failed")
        return build_error_response(
            "RESEARCH_CHAIN_FAILED",
            str(exc),
            recovery_options=[
                "Check arxiv/github/rag/web tool availability",
                "Retry with fewer sources",
            ],
        )

    slug = skill_name
    if not slug:
        slug = re.sub(r"[^a-z0-9]+", "-", topic.strip().lower())[:64].strip("-")
    if not slug:
        slug = "skill"
    slug = re.sub(r"-+", "-", slug).strip("-")

    output_base = Path.cwd() / "skills"
    if output_path:
        p = Path(output_path).expanduser().resolve()
        if p.is_dir():
            output_base = p
        else:
            output_base = p.parent

    try:
        skill_dir = scaffold_skill(slug, output_base, overwrite=True)
    except Exception as exc:
        logger.exception("research_first_create: scaffold_skill failed")
        return build_error_response(
            "SCAFFOLD_FAILED",
            str(exc),
            recovery_options=["Check output_path permissions", "Use different skill_name"],
        )

    scaffold_references_from_research(skill_dir, bundle, include_sources_md=True)

    snippets_text = "\n\n".join(s.get("content", str(s))[:800] for s in (bundle.snippets or [])[:25])
    synthesis = bundle.synthesis or "No synthesis available."
    gaps = "\n".join(f"- {g}" for g in (bundle.gaps_remaining or [])[:10])

