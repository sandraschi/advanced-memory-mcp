"""Advanced Skill Creation with MCP 2.14.3 LLM Sampling Integration."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal

from loguru import logger
from pydantic import BaseModel, Field

from advanced_memory.mcp.mcp_instance import mcp
from advanced_memory.mcp.tools.utils import build_error_response


class SkillRequirements(BaseModel):
    """Requirements for skill creation."""

    topic: str = Field(description="The main topic or domain the skill covers")
    expertise_level: Literal["beginner", "intermediate", "advanced", "expert"] = Field(
        description="Target expertise level for the skill"
    )
    use_cases: list[str] = Field(description="Primary use cases for this skill")
    target_audience: str = Field(description="Who will use this skill (developers, designers, etc.)")
    key_concepts: list[str] = Field(description="Essential concepts to cover")
    practical_examples: bool = Field(description="Whether to include practical examples")


class SkillValidation(BaseModel):
    """Validation results for skill content."""

    completeness_score: float = Field(description="0-1 score of content completeness")
    accuracy_score: float = Field(description="0-1 score of factual accuracy")
    clarity_score: float = Field(description="0-1 score of content clarity")
    issues_found: list[str] = Field(description="List of identified issues")
    improvement_suggestions: list[str] = Field(description="Suggestions for enhancement")


class SkillEnhancement(BaseModel):
    """Enhanced skill content generated by LLM."""

    enhanced_description: str = Field(description="Improved skill description")
    additional_sections: dict[str, str] = Field(description="New sections to add")
    improved_examples: list[str] = Field(description="Better practical examples")
    cross_references: list[str] = Field(description="Related skills to reference")


